def clean_toronto_agenda_page(text):
    """
    Remove City of Toronto council/committee interface chrome while
    preserving decisions, recommendations, tracking status, motions,
    votes, speakers, and other substantive public-record content.
    """
    text = safe_text(text)

    line_patterns = [
        r"^\s*Agenda Item History(?:\s*-\s*.*)?\s*$",
        r"^\s*Share\s*$",
        r"^\s*Share to\s*$",
        r"^\s*Facebook\s*$",
        r"^\s*Twitter\s*$",
        r"^\s*LinkedIn\s*$",
        r"^\s*Print\s*$",
        r"^\s*Close\s*$",
        r"^\s*E-mail\s*$",
        r"^\s*Expand All\s*$",
        r"^\s*Collapse All\s*$",
        r"^\s*See also\s*$",
    ]

    for pattern in line_patterns:
        text = re.sub(
            pattern,
            "",
            text,
            flags=re.IGNORECASE | re.MULTILINE
        )

    # Bare interface "Item" label
    text = re.sub(
        r"(?im)^\s*Item\s*$",
        "",
        text
    )

    # Interface-only item identifier
    text = re.sub(
        r"(?im)^\s*Item\s*-\s*\d{4}\.[A-Z]{2,3}\d+\.\d+\s*$",
        "",
        text
    )

    # Isolated historical item identifier
    text = re.sub(
        r"(?im)^\s*\d{4}\.[A-Z]{2,3}\d+\.\d+\s*$",
        "",
        text
    )

    # Inline sharing artifacts
    text = re.sub(
        r"\bShare\s+to\s+(?:Facebook|Twitter|LinkedIn)\b",
        " ",
        text,
        flags=re.IGNORECASE
    )

    return normalize_whitespace(text)


