# PARAGRAPH RECONSTRUCTION
# ============================================================

def reconstruct_paragraphs(text):
    """
    Rejoin PDF-style hard line wraps while preserving headings,
    numbered lists, bullets, URLs, and genuine paragraph boundaries.

    This improves readability and prepares normalized_text for a later,
    separate chunking stage.
    """
    text = safe_text(text)

    if not text.strip():
        return ""

    lines = text.splitlines()
    rebuilt = []
    buffer = []

    # Typical uppercase report headings
    heading_pattern = re.compile(
        r"^[A-Z][A-Z0-9 /&(),:'’–—\-]{3,}$"
    )

    # Numbered / lettered / bullet list starts
    list_pattern = re.compile(
        r"^\s*(?:\d+[\.\)]|[a-zA-Z][\.\)]|[-•])\s+"
    )

    # URLs and explicit link labels
    url_pattern = re.compile(
        r"^(?:https?://|www\.|Link:)",
        flags=re.IGNORECASE
    )

    # Agenda/report labels that should remain structurally separate
    structural_label_pattern = re.compile(
        r"^(?:"
        r"Decision Type:|"
        r"Status:|"
        r"Wards:|"
        r"Origin|"
        r"Summary|"
        r"Recommendations?|"
        r"Financial Impact|"
        r"Decision History|"
        r"Comments?|"
        r"Background|"
        r"Committee Decision|"
        r"City Council Decision|"
        r"Speakers?|"
        r"Motions?|"
        r"Vote"
        r")$",
        flags=re.IGNORECASE
    )

    def flush_buffer():
        if buffer:
            paragraph = " ".join(
                part.strip()
                for part in buffer
                if part.strip()
            )
            if paragraph:
                rebuilt.append(paragraph)
            buffer.clear()

    for line in lines:
        stripped = line.strip()

        # True paragraph boundary
        if not stripped:
            flush_buffer()
            if rebuilt and rebuilt[-1] != "":
                rebuilt.append("")
            continue

        # Preserve headings
        if heading_pattern.match(stripped):
            flush_buffer()
            rebuilt.append(stripped)
            continue

        # Preserve known structural labels
        if structural_label_pattern.match(stripped):
            flush_buffer()
            rebuilt.append(stripped)
            continue

        # Preserve list starts
        if list_pattern.match(stripped):
            flush_buffer()
            rebuilt.append(stripped)
            continue

        # Preserve URLs / source links
        if url_pattern.match(stripped):
            flush_buffer()
            rebuilt.append(stripped)
            continue

        buffer.append(stripped)

    flush_buffer()

    text = "\n".join(rebuilt)

    # Collapse excessive blank lines
    text = re.sub(
        r"\n{3,}",
        "\n\n",
        text
    )

    return text.strip()


