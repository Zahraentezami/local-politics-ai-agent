ITEM_CODE_PATTERN = re.compile(
    r"\b([A-Za-z]{2,3})\s*(\d+)\.(\d+)\b"
)


def normalize_item_codes(text):
    """
    Standardize municipal item codes.

    Examples:
    ex 9.9 -> EX9.9
    Ex9.9  -> EX9.9
    """
    text = safe_text(text)

    def replacement(match):
        letters, first, second = match.groups()
        return f"{letters.upper()}{first}.{second}"

    return ITEM_CODE_PATTERN.sub(
        replacement,
        text
    )


