# AGENDA METADATA / LIST LAYOUT
# ============================================================

def normalize_agenda_metadata_layout(text):
    """
    Improve Toronto agenda formatting by keeping simple metadata labels
    and values together and joining list markers to their first sentence.
    """
    text = safe_text(text)

    labels = [
        "Decision Type",
        "Status",
        "Wards",
    ]

    for label in labels:
        text = re.sub(
            rf"(?im)^({re.escape(label)}):\s*\n\s*([^\n]+)",
            r"\1: \2",
            text
        )

    # Join numbered recommendation marker with first sentence
    text = re.sub(
        r"(?m)^(\d+\.)\s*\n\s*(?=\S)",
        r"\1 ",
        text
    )

    # Join lettered list marker with first sentence
    text = re.sub(
        r"(?m)^([a-zA-Z]\.)\s*\n\s*(?=\S)",
        r"\1 ",
        text
    )

    # Join bullet marker with first sentence
    text = re.sub(
        r"(?m)^([-•])\s*\n\s*(?=\S)",
        r"\1 ",
        text
    )

    return normalize_whitespace(text)


