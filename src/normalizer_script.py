def normalize_local_politics_text(text, source_url=""):
    """
    Source-aware conservative normalization for the Local Politics Search Agent.

    It removes formatting/interface noise, reconstructs readable paragraphs,
    and preserves substantive municipal-record wording and structure.

    Chunking is intentionally NOT performed here.
    """
    text = safe_text(text)

    if not text.strip():
        return ""

    text = normalize_unicode(text)
    text = normalize_item_codes(text)

    url = safe_text(source_url).lower()

    # Source-specific cleaning
    if "secure.toronto.ca/council" in url:
        text = clean_toronto_agenda_page(text)

    elif "waterfrontoronto.ca" in url:
        text = clean_waterfront_toronto_page(text)

    elif "ttc.ca" in url:
        text = clean_ttc_page(text)

    elif "toronto.ca" in url:
        text = clean_toronto_webpage(text)

    # Safe cross-source cleaning
    text = clean_accessibility_boilerplate(text)
    text = clean_pdf_artifacts(text)
    text = remove_common_boilerplate(text)

    # Reconstruct hard-wrapped prose into readable paragraphs
    text = reconstruct_paragraphs(text)

    # Improve agenda-specific metadata/list layout
    if "secure.toronto.ca/council" in url:
        text = normalize_agenda_metadata_layout(text)

    # Final whitespace cleanup
    text = normalize_whitespace(text)

    return text


