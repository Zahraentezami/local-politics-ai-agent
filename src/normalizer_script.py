def generate_quality_flags(row):
    """
    Generate normalization / extraction review flags.
    """
    flags = []

    text = safe_text(
        row.get("normalized_text", "")
    )

    raw_text = safe_text(
        row.get("raw_text", "")
    )

    exceptions = safe_text(
        row.get("V15_Exceptions", "")
    )

    tier = safe_text(
        row.get("V16_Tier", "")
    )

    # Text availability
    if not text.strip():

        if (
            "OUTBOUND_LINK_ONLY" in exceptions
            or "outbound-link-only" in tier
        ):
            flags.append("OUTBOUND_LINK_ONLY")

        elif (
            "FETCH_FAILED" in exceptions
            or "P0-failed" in tier
        ):
            flags.append("FETCH_FAILED")

        elif (
            "ROBOTS_DISALLOWED" in exceptions
            or "robots-blocked" in tier
        ):
            flags.append("ROBOTS_BLOCKED")

        else:
            flags.append("TEXT_EMPTY")

    else:

        if len(text) < 100:
            flags.append("TEXT_VERY_SHORT")

        elif len(text) < 300:
            flags.append("TEXT_SHORT")

    # Possible truncation
    if 480 <= len(raw_text) <= 520:
        flags.append("POSSIBLE_CONNECTOR_TRUNCATION")

    # Redaction review
    if "[PRIVATE_NAME_REDACTED]" in text:
        flags.append("PII_REDACTION_REVIEW")

    if "[EMAIL_REDACTED]" in text:
        flags.append("EMAIL_REDACTED")

    if "[PHONE_REDACTED]" in text:
        flags.append("PHONE_REDACTED")

    if "[ADDRESS_REDACTED]" in text:
        flags.append("ADDRESS_REDACTED")

    # OCR / extraction
    if "OCR_APPLIED" in exceptions:
        flags.append("OCR_USED")

    if "LOW_CONFIDENCE_EXTRACTION" in exceptions:
        flags.append("LOW_EXTRACTION_CONFIDENCE")

    # Date
    date_flag = safe_text(
        row.get(
            "date_normalization_flag",
            ""
        )
    )

    if date_flag:
        flags.append(date_flag)

    return flags


