# ============================================================

def remove_common_boilerplate(text):
    """
    Remove highly generic interface/extraction artifacts.
    """
    text = safe_text(text)

    patterns = [
        r"\bskip to content\b",
        r"\bskip to main content\b",
        r"\bback to top\b",
        r"\bsubscribe!?\b",
        r"\bno results\b",
        r"\bshare this page\b",
        r"\bprint this page\b",
    ]

    for pattern in patterns:
        text = re.sub(
            pattern,
            " ",
            text,
            flags=re.IGNORECASE
        )

    # Standalone extraction labels
    text = re.sub(
        r"(?im)^\s*(image|body)\s*$",
        "",
        text
    )

    # punctuation / separators
    text = re.sub(
        r"(?m)^\s*[|•·!?]\s*$",
        "",
        text
    )

    return normalize_whitespace(text)


