def normalize_date(value):
    """
    Convert recognizable dates to YYYY-MM-DD.

    Returns:
        normalized_date, flag
    """
    if pd.isna(value) or value == "":
        return None, "DATE_MISSING"

    if isinstance(value, (pd.Timestamp, datetime)):
        return (
            pd.Timestamp(value).strftime("%Y-%m-%d"),
            None
        )

    raw = str(value).strip()

    # Explicit DD/MM/YYYY
    match = re.fullmatch(
        r"(\d{1,2})/(\d{1,2})/(\d{4})",
        raw
    )

    if match:
        day, month, year = map(
            int,
            match.groups()
        )

        try:
            parsed = datetime(
                year,
                month,
                day
            )
            return (
                parsed.strftime("%Y-%m-%d"),
                None
            )
        except ValueError:
            return raw, "DATE_INVALID"

    parsed = pd.to_datetime(
        raw,
        errors="coerce",
        dayfirst=True
    )

    if not pd.isna(parsed):
        return (
            parsed.strftime("%Y-%m-%d"),
            None
        )

    return raw, "DATE_UNPARSED"


