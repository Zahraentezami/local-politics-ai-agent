# TEXT HASH
# ============================================================

def create_text_hash(text):
    """
    Create a SHA-256 hash from normalized text.

    URL is intentionally excluded so identical content at different URLs
    can potentially be detected.
    """
    text = safe_text(text)

    if not text.strip():
        return ""

    canonical = normalize_whitespace(
        normalize_unicode(text)
    )

    return hashlib.sha256(
        canonical.encode("utf-8")
    ).hexdigest()


